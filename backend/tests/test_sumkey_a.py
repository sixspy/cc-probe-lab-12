"""失败测甲：错键正式汇总行仍写入现行，则红。

分层：结栏物化 / 汇总键契约 / 站点汇总账读模型。
硬约束：
- 汇总编号与分组键同票（确定性契约键，不得带随机尾巴）。
- 写汇总键与缓冲消耗同成败。
- 故意错键：切流账册拒收，或现行读模型无错键（错键至多进只读归档）。
"""
from __future__ import annotations

from app.services import 装载, 结栏, 目录, 夹具


def _灌契约内成片():
    return 装载.装一批(夹具.读取("入栏成汇总样例"))


def test_甲1_汇总编号即契约票_无随机尾巴():
    _灌契约内成片()
    结 = 结栏.结当前栏()
    assert 结["汇总数"] == 2

    rows = 目录.汇总列表()
    assert len(rows) == 2
    for r in rows:
        期望票 = f"汇-{r['栏号']}-{r['站点键']}-{r['指标键']}"
        # 汇总编号必须与站点+指标分组键同票
        assert r["汇总编号"] == 期望票
        # 物化行必须钉住现行契约指纹与契约键
        assert r.get("契约键") == 期望票
        assert r.get("契约指纹")
        assert r.get("裁决", "契约对齐") == "契约对齐"
        # 旧实现的随机尾巴形态不得复现
        assert len(r["汇总编号"].rsplit("-", 1)[-1]) != 6 or r["汇总编号"] == 期望票


def test_甲2_裁决接口可回读契约键():
    """新增只读接口：汇总键裁决，须能把现行汇总回读到契约。"""
    _灌契约内成片()
    结栏.结当前栏()

    裁决 = 目录.汇总键裁决()
    assert 裁决["契约"]["形态"] == "栏号+站点+指标"
    assert 裁决.get("对齐") is True
    现行 = 裁决["现行"]
    assert len(现行) == 2
    for item in 现行:
        assert item["裁决"] == "契约对齐"
        assert item["现行可回读契约"] is True
        assert item["契约回读键"] == f"汇-{item['栏号']}-{item['站点键']}-{item['指标键']}"


def test_甲3_故意错键_现行无错键_拒收或归档():
    _灌契约内成片()
    # 调用方拿着一枚与现行账册不一致的旧/错指纹来结栏
    报 = 结栏.结当前栏({"期望指纹": "指纹-故意错键-不存在"})

    # 形态一：切流账册直接拒回刷
    被拒 = bool(报.get("错误") or 报.get("拒收") or 报.get("拒绝"))

    现行 = 目录.汇总列表()
    全量 = 目录.汇总列表(现行_only=False)
    裁决 = 目录.汇总键裁决()

    # 无论拒收还是双写归档，现行读模型里都不得有错键正式行
    错键现行 = [
        r for r in 现行
        if r["汇总编号"] != f"汇-{r['栏号']}-{r['站点键']}-{r['指标键']}"
        or r.get("裁决") == "错键"
    ]
    assert 错键现行 == [], f"错键正式汇总行混入现行: {错键现行}"

    归档 = 目录.错键归档列表()
    形态二留痕 = bool(归档) and any(x.get("裁决") in ("错键", "指纹不符", "拒收") for x in 归档)

    # 必须择一形态落地：明确拒收，或错键进了只读归档
    assert 被拒 or 形态二留痕, "错键既未被切流拒收，也未进只读归档"

    # 同成败：拒收形态下缓冲不得被消耗（仍可正确重结）
    if 被拒 and not 形态二留痕:
        在栏 = 目录.缓冲列表("在栏")
        assert len(在栏) == 3
        重结 = 结栏.结当前栏()
        assert 重结["汇总数"] == 2

    # 裁决须能区分：这组键当前不可回读为契约对齐（尚无现行正式汇总）
    assert 裁决["对齐"] in (True, False)  # 结构存在即可，区分度见乙测


def test_甲4_回刷错键汇总不得入现行():
    """拒回刷：直接回刷一条错键正式汇总，也不得写进现行账。"""
    _灌契约内成片()
    错行 = [{
        "汇总编号": "汇-B-demo-站-河东-PM25-deadbe",  # 随机错键尾巴
        "栏号": "B-demo",
        "站点键": "站-河东",
        "指标键": "PM25",
        "报文数": 2,
        "均值": 36.25,
        "契约指纹": "指纹-故意错键-不存在",
    }]
    报 = 结栏.回刷汇总({"汇总": 错行})
    assert 报.get("错误") or 报.get("拒收") or 报.get("拒收数", 0) >= 1

    现行编号 = [r["汇总编号"] for r in 目录.汇总列表()]
    assert "汇-B-demo-站-河东-PM25-deadbe" not in 现行编号

    裁决 = 目录.汇总键裁决()
    影子编号 = [x.get("汇总编号") for x in 裁决.get("影子", [])]
    # 若没有明确拒收报错，则错键必须能在影子/归档侧被找到
    if not (报.get("错误") or 报.get("拒收")):
        assert "汇-B-demo-站-河东-PM25-deadbe" in 影子编号
